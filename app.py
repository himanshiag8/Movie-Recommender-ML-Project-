#fetch_poster() Function
import requests

import os
API_KEY = os.getenv("TMDB_API_KEY") # TMDB API key

def fetch_poster(movie_id):
    # Construct the URL to fetch movie details using TMDB API
    url = f'https://api.themoviedb.org/3/movie/{movie_id}?api_key={API_KEY}&language=en-US'

    # Send a GET request to the API and convert the response to JSON
    data = requests.get(url).json()

    # Extract the poster path from the response
    poster_path = data.get('poster_path')

    # If a poster path exists, create the full URL and return it
    if poster_path:
        full_path = "https://image.tmdb.org/t/p/w500" + poster_path
        return full_path
    else:
    # If no poster is available, return None
        return None

