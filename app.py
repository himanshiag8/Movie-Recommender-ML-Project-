# Gradio interface function
def recommend_movies(movie_name):
    try:
        # Call the recommended() function to get recommended movies
        # It should return a list of (title, movie_id) tuples
        recommendations = recommended(movie_name)

        # Lists to store poster URLs and movie titles
        movie_posters = []
        movie_titles = []

        # Loop through each recommended movie
        for title, movie_id in recommendations:
            movie_titles.append(title)    # Add the title to the list
            movie_posters.append(fetch_poster(movie_id))   # Fetch and add the poster URL

        # Combine poster URLs and titles into a list of tuples and return
        return [(poster, title) for poster, title in zip(movie_posters, movie_titles)]

    except:
        # If an error occurs (e.g., movie not found), return a placeholder image with a message
        return [("https://via.placeholder.com/150", "Movie not found. Try another.")]

