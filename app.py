"""**Build a recommender function using this similarity matrix.**"""

# returns 5 recommended movies and movie_id function

def recommended(movie):
  # Finds the index of the selected movie in the dataset
  movie_index=new_df[new_df['title'].str.lower() == movie.lower()].index[0]

  # Retrieves similarity scores for the selected movie
  distance=similarity[movie_index]

  # Gets top 5 similar movies (excluding the movie itself)
  movie_list=sorted(list(enumerate(distance)),reverse=True,key=lambda x:x[1])[1:6]

  recommendations=[]
  for i in movie_list:
    movie_id= new_df.iloc[i[0]].movie_id
    title= new_df.iloc[i[0]].title
    recommendations.append((title,movie_id))
  return recommendations

